"""Build the Pages site, the social card and the OG card from `promcast scan` output.

Every figure on the pages is read from docs/design/fleet-scan.json (a scan of a synthetic
fleet forecast by toto-2.0-22m, regenerated by scripts/synthetic_fleet.py), so no number is
typed into a template. The timetable is drawn by scripts/timetable.py from the paths in
docs/design/fleet-paths.json (scripts/fleet_paths.py). The terminal boards are the SVG the CLI
exports; this script only adds a transparent overlay for hover and focus.

    uv run python scripts/build_site.py            # pages, then social-preview.png and og.png
    uv run python scripts/build_site.py --no-png   # pages only, no browser needed
"""

import argparse
import html
import json
import os
import re
import shutil
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import timetable
from playwright.sync_api import sync_playwright
from render_board import load

from promcast.shell import board
from promcast.shell.scan import ScanDocument, ScanResult, ScanSkipped, redact

ROOT = Path(__file__).resolve().parents[1]
SCAN = ROOT / "docs/design/fleet-scan.json"
PATHS = ROOT / "docs/design/fleet-paths.json"
SITE = ROOT / "site"
PNG = ROOT / "docs/design/social-preview.png"
PAPER = "#efece4"  # --paper in site/style.css
GRAFANA = ROOT / "docs/design/grafana-first-screen.png"
GRAFANA_FACTS = ROOT / "docs/design/grafana-first-screen.json"
BRAVE = "/Applications/Brave Browser.app/Contents/MacOS/Brave Browser"
PAST_FREE = 0.031  # the same value the tests use for an already-breached series
CELL, LINE, LEFT, TOP, INSET = 12.2, 24.4, 9, 41, 1.5
WIDE, NARROW, STATES = 80, 44, 144
BOARD_HORIZON_S = 4 * 3600


def x_at(geo: board.Geometry, cell: float) -> float:
    """SVG x of a lane cell."""
    return LEFT + (geo.lane_col + cell) * CELL


def y_of(geo: board.Geometry, lane: int) -> float:
    """SVG y of a lane's line box."""
    return TOP + INSET + (geo.first_lane_line + lane * geo.line_stride) * LINE


def phrase(row_name: str, promcast: float | None, linear: float | None) -> str:
    """The sentence a lane's gap bracket says, from the two breach times."""
    if promcast is None and linear is not None:
        return "predict_linear predicts a crossing; Promcast does not"
    if promcast is not None and linear is not None:
        gap = board.clock(abs(linear - promcast))
        return f"predict_linear is {gap} {'later' if linear > promcast else 'earlier'}"
    return row_name


def overlay(result: ScanResult, width: int) -> str:
    """Hit areas with gap brackets, plus the scrub line that reads the time under the pointer."""
    geo = board.geometry(result, width)
    doc = result.document
    lane_w = geo.size * CELL
    x0 = x_at(geo, 0.5)  # a cell's centre is its moment, the same convention as the ticks
    top = y_of(geo, 0)
    bottom = y_of(geo, len(doc.rows) - 1) + LINE
    parts = [f'<g class="ov" data-x0="{x0}" data-w="{lane_w}" data-span="{geo.span}">']
    for i, row in enumerate(doc.rows):
        cross, diamond = board.marks(row, doc.origin_ts, geo.span, geo.size)
        p = None if row.promcast_breach_ts is None else row.promcast_breach_ts - doc.origin_ts
        lin = None if row.linear_breach_ts is None else row.linear_breach_ts - doc.origin_ts
        y = y_of(geo, i)
        name = " ".join(row.labels[k] for k in row.show_labels if k in row.labels)
        label = html.escape(
            f"{name}: Promcast "
            + (board.clock(p) if p is not None else "clear")
            + ", predict_linear "
            + (board.clock(lin) if lin is not None else "clear")
        )
        bracket = ""
        mid = y + LINE / 2
        if cross is not None and diamond is not None and cross > 0:
            a, b = sorted((x_at(geo, cross + 0.5), x_at(geo, diamond + 0.5)))
            shape = f"M{a:.1f} {mid - 6:.1f}v12m0-6h{b - a:.1f}m0-6v12"
            bracket = (
                f'<path class="gap-line under" d="{shape}"/><path class="gap-line" d="{shape}"/>'
            )
        parts.append(
            f'<g class="hit" tabindex="0" role="img" aria-label="{label}" '
            f'data-gap="{html.escape(phrase(name, p, lin))}">'
            f'<rect x="{LEFT}" y="{y:.1f}" width="{width * CELL:.1f}" height="{LINE}"/>'
            f"{bracket}</g>"
        )
    chip_y = bottom + len(doc.skipped) * LINE + 17
    parts.append(
        f'<line class="scrub" x1="{x0}" x2="{x0}" y1="{top - 8:.1f}" y2="{bottom + 4:.1f}"/>'
        f'<text class="chip" x="{x0}" y="{chip_y:.1f}" text-anchor="middle"></text>'
    )
    parts.append("</g>")
    return "".join(parts)


def terminal_svg(result: ScanResult, width: int) -> str:
    """Match the 12.2 px Rich cell to Martian Mono's 0.75 em advance."""
    return board.scan_svg(result, width=width).replace("font-size: 20px;", "font-size: 16.2667px;")


def sheet_svg(
    doc: ScanDocument, paths: dict[str, Any], size: timetable.Sheet, rest_s: float, key: str
) -> str:
    """Label forecast crossings without implying that alert events were replayed."""
    svg = timetable.svg(doc, paths, size, rest_s, key)
    for old, new in (
        (">unpaged<", ">difference<"),
        ("where predict_linear paged first", "earlier for predict_linear"),
        ("a page Promcast", "linear crosses"),
        ("never sends", "Promcast does not"),
        (">page</text>", ">limit</text>"),
    ):
        svg = svg.replace(old, new)
    return svg


def board_svg(result: ScanResult, width: int) -> str:
    """The CLI's SVG with the overlay, its lead colour set in the page's paper.

    Its own window rim is dropped too, so the export sits flush as the page's one dark slab.
    """
    svg = terminal_svg(result, width).replace(board.HIVIS.lower(), PAPER)
    svg = svg.replace(' stroke="rgba(255,255,255,0.35)" stroke-width="1"', "", 1)
    svg = svg.replace('<svg class="rich-terminal"', '<svg class="rich-terminal" role="group"', 1)
    return svg.replace("</svg>", overlay(result, width) + "</svg>")


def events(result: ScanResult) -> list[dict[str, object]]:
    """Moments on the shared axis, each with the sentence the story shows when it passes."""
    doc = result.document
    out: list[dict[str, object]] = [
        {"t": 0, "kind": "now", "text": f"Now. {len(doc.rows)} series on one clock."}
    ]
    for row in doc.rows:
        name = " ".join(row.labels[k] for k in row.show_labels if k in row.labels)
        p = None if row.promcast_breach_ts is None else row.promcast_breach_ts - doc.origin_ts
        lin = None if row.linear_breach_ts is None else row.linear_breach_ts - doc.origin_ts
        if p is not None:
            tail = (
                " predict_linear sees nothing."
                if lin is None
                else f" predict_linear says {board.clock(lin)}, "
                f"{board.clock(abs(lin - p))} {'later' if lin > p else 'earlier'}."
            )
            out.append(
                {"t": p, "kind": "x", "text": f"Promcast predicts {name} crosses its limit.{tail}"}
            )
        if lin is not None:
            if p is None:
                text = f"predict_linear predicts {name} crosses; Promcast predicts no crossing."
            elif lin < p:
                early = board.clock(p - lin)
                text = f"predict_linear says {name} fills here, {early} before Promcast."
            else:
                late = board.clock(lin - p)
                text = f"predict_linear predicts {name} crosses {late} after Promcast."
            out.append({"t": lin, "kind": "d", "text": text})
    return sorted(out, key=lambda event: float(str(event["t"])))


def grafana_caption(threshold: str) -> str:
    """One sentence on the Grafana frame, with the two times the panel shows.

    The demo's disk pages when it is full, not at the sheet's threshold, and the sentence says
    so, as the two pictures would otherwise seem to disagree on where the page line is.
    """
    lead = f"The Compose demo's synthetic disk pages at 0 B, not {threshold} % free"
    if not GRAFANA_FACTS.exists():
        return f"{lead}."
    facts = json.loads(GRAFANA_FACTS.read_text(encoding="utf-8"))
    linear = facts["linear_minutes"]
    # Written the way the panel prints them, so the sentence and the capture read the same.
    said = "has no breach forecast" if linear is None else f"{linear:.1f} min"
    return f"{lead}: Promcast {facts['promcast_minutes']:.1f} min, predict_linear {said}."


def scenarios(base: ScanResult) -> dict[str, ScanResult]:
    """The same fleet in four states, derived from the scan document and nothing else.

    The boards are drawn as `promcast scan` prints them with a shorter horizon: every breach in
    the fleet falls inside it, so the rows are the same and the axis has no empty hours.
    """
    doc = base.document
    latest = max(
        ts - doc.origin_ts
        for r in doc.rows
        for ts in (r.promcast_breach_ts, r.linear_breach_ts)
        if ts is not None
    )
    if latest > BOARD_HORIZON_S:
        raise SystemExit(
            "error: a breach falls past the board's horizon\nnext:  raise BOARD_HORIZON_S"
        )
    doc = doc.model_copy(
        update={"rows": [r.model_copy(update={"horizon_s": BOARD_HORIZON_S}) for r in doc.rows]}
    )
    base = ScanResult(doc, base.targets, base.dropped, base.total, base.forecasts_per_s)
    first = doc.rows[0].model_copy(
        update={
            "value": PAST_FREE,
            "promcast_breach_ts": doc.origin_ts,
            "linear_breach_ts": doc.origin_ts - 60,
        }
    )
    past = doc.model_copy(update={"rows": [first, *doc.rows[1:]]})
    warm_items = [
        ScanSkipped(target=r.target, labels=r.labels, reason="too_short", warmup_minutes=70)
        for r in doc.rows
    ] + [item.model_copy(update={"warmup_minutes": 70}) for item in doc.skipped]
    warm = doc.model_copy(update={"rows": [], "skipped": warm_items})
    return {
        "populated": base,
        "past": ScanResult(past, [], 0, 0, 0),
        "redact": ScanResult(redact(doc), [], 0, 0, 0),
        "warming": ScanResult(warm, [], 0, 0, 0),
    }


def when(event: dict[str, object], origin: int) -> str:
    """The time label of an event: its clock time, then `now` or `+1h 15m`."""
    seconds = float(str(event["t"]))
    offset = "now" if seconds == 0 else "+" + board.clock(seconds)
    return f"<b>{timetable.hm(origin + seconds)}</b> {offset}"


def arrivals(result: ScanResult) -> str:
    """The timetable's arrivals column: one row per series, then those still warming up."""
    doc = result.document
    rows: list[str] = []
    for i, row in enumerate(doc.rows):
        a, b = row.promcast_breach_ts, row.linear_breach_ts
        rows.append(
            f'<tr data-i="{i}"><th scope="row">'
            f'<button type="button" aria-pressed="{str(i == 0).lower()}">'
            f"{html.escape(timetable.name(row.labels))}"
            f"<small>{html.escape(timetable.place(row.labels, row.target))}</small></button></th>"
            f'<td class="{"pc" if a else "clear"}">{timetable.hm(a) if a else "clear"}</td>'
            f'<td class="{"ln" if b else "clear"}">{timetable.hm(b) if b else "clear"}</td></tr>'
        )
    rows.extend(
        f'<tr class="warm"><th scope="row"><span>{html.escape(timetable.name(item.labels))}'
        f"<small>{html.escape(timetable.place(item.labels, item.target))}</small></span></th>"
        '<td colspan="2">warming up</td></tr>'
        for item in doc.skipped
    )
    return "".join(rows)


def fill(template: str, values: dict[str, str]) -> str:
    """Replace every {{key}} and fail on a placeholder that has no value."""
    for key, value in values.items():
        template = template.replace("{{" + key + "}}", value)
    if left := re.findall(r"\{\{\w+\}\}", template):
        raise SystemExit(f"error: unfilled placeholders {left}\nnext:  add them to build_site.py")
    return _outside_svg(template)


DURATION = re.compile(r"(\b\d+h) (\d{2}m\b)")


def _outside_svg(page: str) -> str:
    """Keep a duration such as 2h 00m on one line, without touching the boards' own text."""
    parts = re.split(r"(<svg.*?</svg>)", page, flags=re.S)
    return "".join(p if p.startswith("<svg") else DURATION.sub("\\1\u00a0\\2", p) for p in parts)


def render_png(page: Path, target: Path) -> None:
    """Screenshot a page at 1280 by 640 with the Brave binary the repo already uses."""
    executable = os.environ.get("PROMCAST_BROWSER") or BRAVE
    with sync_playwright() as playwright:
        browser = playwright.chromium.launch(executable_path=executable)
        view = browser.new_page(viewport={"width": 1280, "height": 640})
        view.goto(page.as_uri())
        view.evaluate("document.fonts.ready")
        view.screenshot(path=str(target))
        browser.close()


def main() -> None:
    """Write site/index.html and site/social.html; render the PNG cards unless --no-png."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--no-png", action="store_true")
    parser.add_argument(
        "--check", action="store_true", help="verify committed page and board output"
    )
    arguments = parser.parse_args()
    base = load(SCAN)
    doc = base.document
    first = doc.rows[0]
    if not (first.promcast_breach_ts and first.linear_breach_ts):
        raise SystemExit(
            "error: the first row has no breach\nnext:  rescan with a series that fills"
        )
    if first.linear_breach_ts <= first.promcast_breach_ts:
        raise SystemExit(
            "error: the headline says predict_linear is late, and here it is not\n"
            "next:  rescan, or rewrite the headline in site/_templates"
        )
    origin = doc.origin_ts
    names = " ".join(first.labels[key] for key in first.show_labels)
    states = scenarios(base)
    lead_s = first.promcast_breach_ts - origin
    # The sheet rests where the second stamp lands: both arrivals and the bar between them.
    rest_s = first.linear_breach_ts - origin
    paths = timetable.load_paths(PATHS)
    loss = next(
        r
        for r in doc.rows
        if r.promcast_breach_ts and r.linear_breach_ts and r.linear_breach_ts < r.promcast_breach_ts
    )
    spare = next(r for r in doc.rows if r.linear_breach_ts and not r.promcast_breach_ts)
    stamp = datetime.fromtimestamp(origin, UTC).strftime("%d %b %Y").lstrip("0")
    source_year = re.search(r"Paris to Lyon, (\d{4})", (ROOT / "DESIGN.md").read_text())
    if source_year is None:
        raise ValueError("DESIGN.md needs the timetable source year")
    values = {
        "marey_year": source_year[1],
        "name": names,
        "host": names.split()[0],
        "place": timetable.place(first.labels, first.target),
        "lead": board.clock(lead_s),
        "linear": board.clock(first.linear_breach_ts - origin),
        "gap": board.clock(first.linear_breach_ts - first.promcast_breach_ts),
        "late": timetable.minutes(first.linear_breach_ts - first.promcast_breach_ts),
        "p_at": timetable.hm(first.promcast_breach_ts),
        "d_at": timetable.hm(first.linear_breach_ts),
        "now_at": timetable.hm(origin),
        "date": stamp,
        "threshold": f"{first.threshold * 100:g}",
        "loss": timetable.name(loss.labels),
        "loss_gap": board.clock((loss.promcast_breach_ts or 0) - (loss.linear_breach_ts or 0)),
        "spare": timetable.name(spare.labels),
        "spare_at": timetable.hm(spare.linear_breach_ts or 0),
        "model": doc.model,
        "series": str(len(doc.rows)),
        "warming": str(len(doc.skipped)),
        "sheet": sheet_svg(doc, paths, timetable.WIDE, rest_s, "w"),
        "sheet_narrow": sheet_svg(doc, paths, timetable.NARROW, rest_s, "n"),
        "sheet_social": sheet_svg(doc, paths, timetable.SOCIAL, rest_s, "s"),
        "still_s": str(round(rest_s)),
        "rest_at": timetable.hm(first.linear_breach_ts),
        "ahead_s": str(timetable.AHEAD_S),
        **{
            f"rd_{key}": html.escape(value)
            for key, value in timetable.reading(
                timetable.trains(doc, paths)[0], paths["step_s"], origin, rest_s
            ).items()
        },
        "page_data": timetable.page_data(doc, paths),
        "arrivals": arrivals(base),
        "grafana_caption": grafana_caption(f"{first.threshold * 100:g}"),
        "events_html": "".join(
            f'<li data-t="{e["t"]}" data-kind="{e["kind"]}">'
            f'<span class="when">{when(e, origin)}</span>'
            f'<span class="what">{html.escape(str(e["text"]))}</span></li>'
            for e in events(base)
        ),
        "past_free": f"{PAST_FREE * 100:g}",
    }
    values["rd_say"] = "Predicted crossing gap"
    values["rd_left"] = values["gap"]
    for key, result in states.items():
        values[f"state_{key}"] = board_svg(result, STATES)
        values[f"state_{key}_narrow"] = board_svg(result, NARROW)
    artifacts = {
        "board.svg": terminal_svg(base, WIDE),
        "board-narrow.svg": terminal_svg(base, NARROW),
        **{
            page + ".html": fill((SITE / "_templates" / (page + ".html")).read_text(), values)
            for page in ("index", "social")
        },
    }
    if arguments.check:
        stale = [
            name
            for name, content in artifacts.items()
            if not (SITE / name).exists() or (SITE / name).read_text() != content
        ]
        if stale:
            raise SystemExit(
                "stale site output: "
                + ", ".join(stale)
                + "; run uv run python scripts/build_site.py --no-png"
            )
        return
    for name, content in artifacts.items():
        (SITE / name).write_text(content, encoding="utf-8")
    if GRAFANA.exists():
        shutil.copyfile(GRAFANA, SITE / "grafana.png")
    if not arguments.no_png:
        render_png(SITE / "social.html", PNG)
        shutil.copyfile(PNG, SITE / "og.png")


if __name__ == "__main__":
    main()
